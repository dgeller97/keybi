import assert from "node:assert/strict";
import {art,filter,open,rename,save,settled,studio,visual} from "./portfolio-ui.mjs";
import {setReaderAccess} from "./hospital-reading.mjs";

export async function verifyImportedReaderFilters() {
  const report="Invoice reader checks",title="Invoice amount";
  const total=p=>art(p,title).locator(".kpi").innerText();
  const apply=async p=>{await p.locator("dialog button[type=submit]").click();await settled(p);};
  await studio(async p=>{
    await p.locator("#home [data-action=new]").click();await rename(p,report,"Which invoices are included?");
    const chooser=p.waitForEvent("filechooser");await p.locator(".ribbon [data-action=import]").click();
    const lines=["Desk,Active,Batch,Amount","North,Y,0,10",",Y,0,20","(Blank),Y,0,30","All values,Y,0,40","South,N,0,100","South,Y,2,50"];
    for (let i=0;i<155;i++) lines.push("Office"+String(i).padStart(3,"0")+",Y,0,1");
    await (await chooser).setFiles({name:"Invoices.csv",mimeType:"text/csv",buffer:Buffer.from(lines.join("\n"))});
    await p.getByTitle("Invoices.Amount",{exact:true}).waitFor();
    await visual(p,"card",title,[],["Invoices · Amount"],[18,18,410,140]);
    await filter(p,"report","Invoices · Active","Y");
    await filter(p,"page","Invoices · Desk","North");
    await filter(p,"visual","Invoices · Batch","0");
    await p.locator(".ribbon [data-action=bookmarks]").click();
    await p.getByLabel("New bookmark name").fill("North invoices");
    await p.getByRole("button",{name:"Add current view"}).click();
    await p.locator("[data-tab=Filters]").click();
    await setReaderAccess(p,"report",0,"hidden");await setReaderAccess(p,"visual",0,"locked");
    await save(p);
  });
  await studio(async p=>{
    await open(p,report);await p.getByRole("button",{name:"Reading view",exact:true}).click();await settled(p);
    for(const [label,value,expected] of [["(Blank)",null,20],['"(Blank)"',null,30],['"All values"',null,40],["Enter exact value…","Office154",1],["All values",null,255]]) {
      await art(p,title).locator("[data-view-filters]").click();const d=p.getByRole("dialog");
      assert.match(await d.locator(".locked-filter").innerText(),/Batch · 0 Locked/);
      assert.equal(await d.getByText("Active",{exact:true}).count(),0);
      await d.getByLabel("Desk",{exact:true}).selectOption({label});
      if(value) await d.getByLabel("Exact value for Desk").fill(value);
      await apply(p);assert.equal(await total(p),String(expected));
    }
    await p.locator("[data-action=reader-bookmarks]").click();await p.getByRole("button",{name:"North invoices",exact:true}).click();await settled(p);
    assert.equal(await total(p),"10");
    await art(p,title).locator("[data-view-filters]").click();const d=p.getByRole("dialog");
    assert.match(await d.locator(".locked-filter").innerText(),/Batch · 0 Locked/);
    assert.equal(await d.getByLabel("Active",{exact:true}).count(),0);
    await p.keyboard.press("Escape");await p.locator("[data-action=toggle-reading]").click();await settled(p);
    await art(p,title).locator("[data-view-filters]").click();await setReaderAccess(p,"visual",0,"editable");
    await p.locator("[data-action=toggle-reading]").click();await settled(p);
    await art(p,title).locator("[data-view-filters]").click();
    await d.getByLabel("Desk",{exact:true}).selectOption({label:"All values"});
    await d.getByLabel("Batch",{exact:true}).selectOption({label:"Enter exact value…"});
    await d.getByLabel("Exact value for Batch").fill("invalid");await d.getByRole("button",{name:"Apply"}).click();
    await d.getByRole("alert").getByText("Enter a numeric filter value.").waitFor();
    await d.getByLabel("Exact value for Batch").fill("2");await apply(p);assert.equal(await total(p),"50");
    await p.locator("[data-action=reader-reset]").click();await settled(p);assert.equal(await total(p),"10");
  });
  await studio(async p=>{
    await open(p,report);
    const chooser=p.waitForEvent("filechooser");await p.locator(".ribbon [data-action=import]").click();
    let finishImport;
    const delayed=new Promise(resolve=>{finishImport=resolve;});
    await p.route("**/api/import",async r=>{await delayed;await r.continue();},{times:1});
    const started=p.waitForRequest(r=>r.url().endsWith("/api/import"));
    await (await chooser).setFiles({name:"Incoming.csv",mimeType:"text/csv",buffer:Buffer.from("Desk,Fee\nEast,15\n")});
    await started;await p.locator("[data-action=toggle-reading]").click();finishImport();
    await p.locator("body.reading").waitFor();await settled(p);
    await p.locator("[data-action=toggle-reading]").click();await settled(p);
    await p.getByTitle("Incoming.Fee",{exact:true}).waitFor();
    let finishSave;
    const held=new Promise(resolve=>{finishSave=resolve;});
    await p.route("**/api/reports",async r=>{await held;await r.continue();},{times:1});
    const saving=p.waitForRequest(r=>r.method()==="POST"&&r.url().endsWith("/api/reports"));
    await p.locator("header [data-action=save]").click();await saving;
    await p.locator("[data-action=toggle-reading]").click();finishSave();
    await p.locator("body.reading").waitFor();await settled(p);
    await p.locator("[data-action=toggle-reading]").click();await settled(p);
    assert.equal(await p.locator("#save-state").innerText(),"Saved");
    await rename(p,report+" revised","Which invoices are included?");
    await p.locator("[data-action=toggle-reading]").click();await settled(p);
    await p.locator("[data-action=reader-filters]").click();
    await p.getByLabel("Desk",{exact:true}).selectOption({label:"All values"});await apply(p);
    assert.equal(await total(p),"255");
    await p.getByRole("button",{name:"Workspace home"}).click();
    await p.getByRole("button",{name:"Save and continue"}).click();await p.locator("#home h1").waitFor();
    await open(p,report+" revised");assert.equal(await total(p),"10");
    await p.getByTitle("Incoming.Fee",{exact:true}).waitFor();
  });
  await studio(async p=>{
    await open(p,report+" revised");await art(p,title).locator(".vhead").click();await p.locator("[data-tab=Filters]").click();
    await p.getByRole("button",{name:"Edit Desk filter",exact:true}).click();
    const d=p.getByRole("dialog"),box=name=>d.getByRole("checkbox",{name,exact:true});
    await p.getByLabel("Condition",{exact:true}).selectOption("in");
    await box("North").uncheck();await d.getByRole("button",{name:"Apply",exact:true}).click();
    await d.getByRole("alert").filter({hasText:"Select at least one"}).waitFor();
    await box("(Blank)").check();await box('"(Blank)"').check();
    await d.getByRole("button",{name:"Next values"}).click();await box("Office154").check();
    await d.getByRole("button",{name:"Previous values"}).click();assert.ok(await box("Office154").isChecked());
    const search=d.getByRole("searchbox",{name:"Search values"});
    await search.fill("fIcE15");await box("Office150").waitFor();
    assert.deepEqual((await d.locator("[data-members] label").allTextContents()).sort(),["Office150","Office151","Office152","Office153","Office154"]);
    await search.fill("No such desk");await d.getByText("No matching values",{exact:true}).waitFor();
    await search.fill("");await box("North").waitFor();assert.ok(await box("Office154").isChecked());
    await d.getByLabel("Exact value",{exact:true}).fill("Unposted office");await d.getByRole("button",{name:"Add value"}).click();
    await apply(p);assert.equal(await total(p),"51");await save(p);
    await p.reload();await art(p,title).waitFor();await settled(p);assert.equal(await total(p),"51");
    await art(p,title).locator("[data-view-filters]").click();await p.getByRole("button",{name:"Edit Batch filter",exact:true}).click();
    await p.getByLabel("Condition",{exact:true}).selectOption("in");await box("2").check();await apply(p);
    await setReaderAccess(p,"visual",0,"locked");await save(p);
    await p.getByRole("button",{name:"Reading view",exact:true}).click();await settled(p);
    await art(p,title).locator("[data-view-filters]").click();
    assert.match(await d.locator(".locked-filter").innerText(),/Batch · 0, 2 Locked/);
    await box("All values").check();await apply(p);assert.equal(await total(p),"305");
    await art(p,title).locator("[data-view-filters]").click();
    await d.getByRole("searchbox",{name:"Search values"}).fill("LL val");
    await box('"All values"').check();
    await apply(p);assert.equal(await total(p),"40");
  });
  console.log("Verified reader filters, selected value lists across pages, null and literal blank, exact entries, saved edits, lock settings and reset.");
}
